export function mergeCategories(current: string[], incoming: string[]): string[] {
  const seen = new Set<string>();
  return [...current, ...incoming].map((category) => category.trim()).filter((category) => {
    const key = category.toLocaleLowerCase("pt-BR");
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}
